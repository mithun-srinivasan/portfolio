const read = (file) => fs.readFileSync(file, "utf8");
const rel = (file) => path.relative(ROOT, file).split(path.sep).join("/");
const warnings = [];

function warn(message) {
  warnings.push(message);
  console.warn(`warning: ${message}`);
}

function writeIfChanged(file, content) {
  const previous = fs.existsSync(file) ? read(file) : null;
  if (previous === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

function escapeAttr(value) {
  return escapeHtml(value);
}

function jsonLd(value) {
  return JSON.stringify(value, null, 2).replace(/</g, "\\u003c");
}

export function formatDate(iso) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso || ""));
  if (!match || !MONTHS[Number(match[2]) - 1]) return String(iso || "");
  return `${match[3]} ${MONTHS[Number(match[2]) - 1]} ${match[1]}`;
}

/* Talks may be exact (YYYY-MM-DD), monthly (YYYY-MM) or legacy (YYYY). */
export function formatTalkDate(value) {
  const match = /^(\d{4})(?:-(\d{2})(?:-(\d{2}))?)?$/.exec(String(value || ""));
  if (!match) return String(value || "");
  const [, year, month, day] = match;
  if (!month || !MONTHS[Number(month) - 1]) return year;
  const label = MONTHS[Number(month) - 1];
  return day ? `${day} ${label} ${year}` : `${label} ${year}`;
}

export function readingTime(markdown) {
  const words = String(markdown)
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/[#>*_`[\]()\-]/g, " ")
    .split(/\s+/)
    .filter(Boolean).length;
  return Math.max(1, Math.ceil(words / 200));
}

export function parseFrontMatter(source) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(String(source));
  if (!match) return { data: {}, body: String(source) };
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const split = line.indexOf(":");
    if (split < 0) continue;
    const key = line.slice(0, split).trim();
    let value = line.slice(split + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    data[key] = value;
  }
  return { data, body: match[2] };
}

