export function loadPosts({ includeDrafts = false } = {}) {
  const posts = [];
  if (!fs.existsSync(POSTS_DIR)) return posts;

  for (const name of fs.readdirSync(POSTS_DIR)) {
    if (!name.endsWith(".md") || name.startsWith("_")) continue;
    const file = path.join(POSTS_DIR, name);
    const { data, body } = parseFrontMatter(read(file));
    const fromName = name.replace(/^\d{4}-\d{2}-\d{2}-/, "").replace(/\.md$/, "");
    const slug = (data.slug || fromName).trim();
    const date = (data.date || name.slice(0, 10)).trim();
    const draft = String(data.draft || "false").toLowerCase() === "true";

    if (!data.title) warn(`${rel(file)}: missing title`);
    if (!data.description) warn(`${rel(file)}: missing description`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) warn(`${rel(file)}: date must be YYYY-MM-DD`);
    if (!/^[a-z0-9-]+$/.test(slug)) warn(`${rel(file)}: slug must be a-z, 0-9 and hyphen only`);

    posts.push({
      file,
      title: (data.title || "Untitled").trim(),
      slug,
      date,
      updated: (data.updated || "").trim(),
      description: (data.description || "").trim(),
      draft,
      tags: (data.tags || "").split(",").map((tag) => tag.trim()).filter(Boolean),
      image: (data.image || "").trim(),
      body,
      minutes: readingTime(body),
      url: `/posts/${slug}.html`,
    });
  }

  const seen = new Set();
  for (const post of posts) {
    if (seen.has(post.slug)) warn(`duplicate slug: ${post.slug}`);
    seen.add(post.slug);
  }

  const visible = includeDrafts ? posts : posts.filter((post) => !post.draft);
  visible.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));
  return visible;
}

export function loadTalks({ includeDrafts = false } = {}) {
  const file = path.join(CONTENT, "talks.json");
  if (!fs.existsSync(file)) return [];
  let talks;
  try {
    talks = JSON.parse(read(file));
  } catch (error) {
    warn(`content/talks.json: ${error.message}`);
    return [];
  }
  if (!Array.isArray(talks)) {
    warn("content/talks.json: expected an array");
    return [];
  }
  const visible = includeDrafts ? talks : talks.filter((talk) => !talk.draft);
  visible.forEach((talk, index) => {
    if (!talk.title) warn(`talks.json[${index}]: missing title`);
    if (!talk.date) warn(`talks.json[${index}]: missing date`);
    else if (!/^\d{4}(-\d{2}(-\d{2})?)?$/.test(String(talk.date))) warn(`talks.json[${index}]: date must be YYYY-MM or YYYY-MM-DD`);
    else if (/^\d{4}$/.test(String(talk.date))) warn(`talks.json[${index}]: "${talk.title}" has no month yet (${talk.date}) — see TODO-FOR-MITHUN.md`);
    if (!talk.url) warn(`talks.json[${index}]: missing url`);
  });
  return visible;
}

