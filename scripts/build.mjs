/* ---------- region patching ---------- */

function replaceRegion(file, name, html) {
  const source = read(file);
  const pattern = new RegExp(`<!-- BEGIN GENERATED: ${name} -->[\\s\\S]*?<!-- END GENERATED: ${name} -->`);
  if (!pattern.test(source)) {
    warn(`${rel(file)}: missing generated region "${name}"`);
    return false;
  }
  return writeIfChanged(file, source.replace(pattern, `<!-- BEGIN GENERATED: ${name} -->\n${html}\n<!-- END GENERATED: ${name} -->`));
}

function applyAssetVersion(file, version) {
  const source = read(file);
  const next = source
    .replace(/(\/assets\/css\/style\.css)(?:\?v=[^"']*)?/g, `$1?v=${version}`)
    .replace(/(\/assets\/js\/script\.js)(?:\?v=[^"']*)?/g, `$1?v=${version}`)
    .replace(/(\/assets\/js\/posts\.js)(?:\?v=[^"']*)?/g, `$1?v=${version}`);
  return writeIfChanged(file, next);
}

function htmlFiles() {
  const files = fs.readdirSync(ROOT)
    .filter((name) => name.endsWith(".html"))
    .map((name) => path.join(ROOT, name));
  const posts = path.join(ROOT, "posts");
  if (fs.existsSync(posts)) {
    files.push(...fs.readdirSync(posts).filter((name) => name.endsWith(".html")).map((name) => path.join(posts, name)));
  }
  return files;
}

function gitLastmod(file) {
  try {
    return execFileSync("git", ["log", "-1", "--format=%cs", "--", rel(file)], { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

